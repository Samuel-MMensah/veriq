// Prompt 9: writes the imported directory as one SQL migration, so local mode (PGlite), the tests and
// Supabase all load the same rows. Rule D1 and item 3 of the prompt: each real facility gets its
// directory facts and one NHIS row with listed_by = nhia (badge B4). Nothing else: no private
// insurer rows (B5), no services, status rows, reports, top-ups or hospital answers.
import type { NhiaFacility } from "./nhia.ts";
import type { LocationMatch } from "./osm.ts";

/** The NHIS insurer, as seeded by reset_demo() (migration 4). */
export const NHIS_INSURER_ID = "a0000000-0000-4000-8000-000000000001";

const lit = (v: string | null) => (v === null ? "null" : `'${v.replace(/'/g, "''")}'`);
const num = (v: number | null) => (v === null ? "null" : String(v));

export function directorySql({
  facilities,
  matches,
  sourceFile,
  sourceDate,
  osmDate,
}: {
  facilities: NhiaFacility[];
  /** One per facility, in the same order. */
  matches: LocationMatch[];
  sourceFile: string;
  /** "YYYY-MM-DD", when the list was taken (data/nhia/SOURCE.md). */
  sourceDate: string;
  /** When the OpenStreetMap extract was taken, for location_checked_at. */
  osmDate: string;
}): string {
  if (facilities.length !== matches.length) throw new Error("One location match per facility.");
  const values = facilities.map((f, i) => {
    const m = matches[i]!;
    const lat = m.location_source === "osm" ? m.lat : null;
    const lng = m.location_source === "osm" ? m.lng : null;
    const checked = m.location_source === "osm" ? lit(osmDate) : "null";
    return `  (${[
      lit(f.name),
      "'Greater Accra'",
      lit(f.district),
      lit(f.area),
      num(lat),
      num(lng),
      lit(f.phone),
      lit(f.source_ref),
      lit(f.nhia_type),
      lit(m.location_source),
      checked,
    ].join(", ")})`;
  });

  return `-- Generated by scripts/import-nhia.ts from data/nhia/${sourceFile} (taken ${sourceDate}) and the
-- OpenStreetMap extract of ${osmDate} (© OpenStreetMap contributors, ODbL). Do not edit by hand:
-- change the data or the importer and run \`node scripts/import-nhia.ts\` again.
-- ${facilities.length} facilities, ${matches.filter((m) => m.location_source === "osm").length} with an OpenStreetMap location.
-- Rule D1: only what the file says. Rule D2: no reports, status rows, top-ups or hospital answers.

-- The NHIS insurer, in case the demo seed has not run yet (same row as reset_demo()).
insert into public.insurers (id, slug, name, kind)
values (${lit(NHIS_INSURER_ID)}, 'nhis', 'NHIS', 'public')
on conflict (id) do nothing;

insert into public.facilities
  (name, region, district, area, lat, lng, phone, source_ref, nhia_type, location_source, location_checked_at,
   source, source_date, is_sample, nhia_listed, verified)
select v.name, v.region, v.district, v.area, v.lat, v.lng, v.phone, v.source_ref, v.nhia_type, v.location_source,
       v.location_checked_at::timestamptz, 'nhia', date ${lit(sourceDate)}, false, true, false
from (values
${values.join(",\n")}
) as v(name, region, district, area, lat, lng, phone, source_ref, nhia_type, location_source, location_checked_at)
on conflict (source, source_ref) where source_ref is not null do update set
  name = excluded.name,
  district = excluded.district,
  area = excluded.area,
  phone = excluded.phone,
  nhia_type = excluded.nhia_type,
  source_date = excluded.source_date,
  -- A location an admin set by hand is never overwritten by a re-import.
  lat = case when facilities.location_source = 'admin' then facilities.lat else excluded.lat end,
  lng = case when facilities.location_source = 'admin' then facilities.lng else excluded.lng end,
  location_checked_at = case when facilities.location_source = 'admin' then facilities.location_checked_at else excluded.location_checked_at end,
  location_source = case when facilities.location_source = 'admin' then 'admin' else excluded.location_source end;

-- Badge B4: "On NHIA list, not checked yet. Call first". Nothing for private insurers (B5).
insert into public.facility_insurers (facility_id, insurer_id, listed_by)
select f.id, ${lit(NHIS_INSURER_ID)}, 'nhia'
from public.facilities f
where f.source = 'nhia'
on conflict (facility_id, insurer_id) do update set listed_by = 'nhia';
`;
}
