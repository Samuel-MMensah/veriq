// Prompt 9: the import report. Rows the importer couldn't read go here, never to the database.
import type { NhiaFacility, RejectedRow } from "./nhia.ts";
import type { LocationMatch } from "./osm.ts";

const cell = (s: string | null) => (s ?? "").replace(/\|/g, "/");

export function importReport({
  facilities,
  rejected,
  matches,
  sourceFile,
  osmDate,
}: {
  facilities: NhiaFacility[];
  rejected: RejectedRow[];
  matches: LocationMatch[];
  sourceFile: string;
  osmDate: string;
}): string {
  const located = matches.filter((m) => m.location_source === "osm").length;
  const reasons = new Map<string, number>();
  for (const m of matches) if (m.location_source === "none") reasons.set(m.reason, (reasons.get(m.reason) ?? 0) + 1);

  const lines = [
    `# NHIA import report: ${sourceFile}`,
    "",
    "Generated by `node scripts/import-nhia.ts`. Do not edit by hand.",
    "",
    `- Facilities imported: ${facilities.length}`,
    `- Rows not read (not in the database): ${rejected.length}`,
    `- Located on OpenStreetMap (extract of ${osmDate}): ${located}`,
    `- Need a location (listed on /admin): ${facilities.length - located}`,
    "",
    "## Rows not read",
    "",
  ];
  if (rejected.length === 0) lines.push("None.");
  else {
    lines.push("| Row | Why | Row as written |", "| --- | --- | --- |");
    for (const r of rejected) lines.push(`| ${r.row} | ${cell(r.reason)} | ${cell(r.raw.join(" · "))} |`);
  }
  lines.push("", "## Why no location was set", "");
  if (reasons.size === 0) lines.push("Every facility has a location.");
  else {
    lines.push("| Reason | Facilities |", "| --- | --- |");
    for (const [reason, n] of [...reasons].sort((a, b) => b[1] - a[1])) lines.push(`| ${cell(reason)} | ${n} |`);
  }
  return `${lines.join("\n")}\n`;
}
